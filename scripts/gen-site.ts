/** Strip terminal colour codes. */
const ANSI = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, "g");

/** The CLI's `--help` output for `args`, at commander's default width and without colour, whatever the terminal. */
async function help(args: string[]): Promise<string> {
  const streams = [process.stdout, process.stderr];
  const saved = streams.map((s) => Object.getOwnPropertyDescriptor(s, "isTTY"));
  for (const s of streams) Object.defineProperty(s, "isTTY", { value: false, configurable: true, writable: true });
  let out = "";
  try {
    await run([...args, "--help"], { stdout: { write: (s: string) => (out += s) }, stderr: { write: () => true }, env: { NO_COLOR: "1" }, color: false });
  } finally {
    streams.forEach((s, i) => {
      const d = saved[i];
      if (d) Object.defineProperty(s, "isTTY", d);
      else delete (s as { isTTY?: boolean }).isTTY;
    });
  }
  return out.replace(ANSI, "").trimEnd();
}

async function cliPage(): Promise<GeneratedFile> {
  const root = await help([]);
  const commands: string[] = [];
  let inCommands = false;
  for (const line of root.split("\n")) {
    if (/^Commands:/.test(line)) inCommands = true;
    else if (/^\S/.test(line)) inCommands = false;
    else if (inCommands) {
      const name = /^ {2}([a-z][\w-]*)/.exec(line)?.[1];
      if (name && name !== "help") commands.push(name);
    }
  }
  const parts = [
    "This page is the CLI's own `--help` output (`packages/cli/src/main.ts`). Global options go before or after the",
    "command. Every command takes `--json`; what it prints is described in [Agents and MCP](/guides/agents), and every",
    "error code and exit code in [Errors](/reference/errors).",
    "",
    "## sponson",
    "",
    "```text",
    root,
    "```",
  ];
  for (const c of commands) parts.push("", `## sponson ${c}`, "", "```text", await help([c]), "```");
  return page("reference/cli", META["reference/cli"]!, ["packages/cli/src/main.ts (sponson --help)"], parts.join("\n"));
}

async function readmePages(router: Router): Promise<Map<string, string[]>> {
  const readme = await read("README.md");
  const { preamble, sections } = splitSections(stripTitle(readme), 2);
  const bodies = new Map<string, string[]>([["index", [preamble]]]);
  const add = (route: string | null, text: string) => {
    if (route) bodies.set(route, [...(bodies.get(route) ?? []), text]);
  };
  for (const s of sections) {
    const route = s.heading in README_SECTIONS ? README_SECTIONS[s.heading]! : "concepts";
    const sub = splitSections(s.text, 3);
    // The page's own section heading is redundant when the section is the whole page (Quick start).
    const head = route === "quickstart" ? sub.preamble.replace(/^## .*\n/, "") : sub.preamble;
    add(route, head);
    for (const ss of sub.sections) add(ss.heading in README_SECTIONS ? README_SECTIONS[ss.heading]! : route, ss.text);
  }
  const out = new Map<string, string[]>();
  for (const [route, texts] of bodies) out.set(route, [toMdx(texts.join("\n\n"), "README.md", router)]);
  return out;
}

async function examplesPage(router: Router): Promise<GeneratedFile> {
  const md = stripTitle(await read("examples/README.md"));
  const plans = (await readdir(join(REPO, "examples"))).filter((f) => f.endsWith(".plan.yaml")).sort();
  const embed = async (file: string) => `\n\n\`\`\`yaml ${file}\n${(await read(`examples/${file}`)).trimEnd()}\n\`\`\``;
  const { preamble, sections } = splitSections(md, 2);
  const parts = [toMdx(preamble, "examples/README.md", router)];
  const shown = new Set<string>();
  for (const s of sections) {
    let text = toMdx(s.text, "examples/README.md", router);
    if (plans.includes(s.heading)) {
      text += await embed(s.heading);
      shown.add(s.heading);
    }
    parts.push(text);
  }
  const rest = plans.filter((p) => !shown.has(p));
  if (rest.length) {
    parts.push("## More examples");
    for (const p of rest) parts.push(`### ${p}${await embed(p)}`);
  }
  return page("reference/examples", META["reference/examples"]!, ["examples/README.md", "examples/*.plan.yaml"], parts.join("\n\n"));
}

/** The ADR files, sorted. */
async function adrFiles(): Promise<string[]> {
  return (await readdir(join(REPO, "docs/adr"))).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort();
}

async function adrPages(router: Router): Promise<GeneratedFile[]> {
  const out: GeneratedFile[] = [];
  for (const file of await adrFiles()) {
    const source = `docs/adr/${file}`;
    const md = await read(source);
    const num = file.slice(0, 4);
    const name = titleOf(md).replace(/^\d+\.\s*/, "").replace(/`/g, "");
    const status = /^## Status\s*\n+([^\n]+)/m.exec(md)?.[1]?.replace(/`/g, "").replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").trim() ?? "";
    const meta: PageMeta = {
      title: `ADR ${num}: ${name}`,
      sidebarTitle: `${num} ${name}`,
      description: `Architecture decision record ${num}. Status: ${status}`.replace(/\s+$/, ""),
    };
    out.push(page(`contributing/adr/${file.slice(0, -3)}`, meta, [source], toMdx(stripTitle(md), source, router)));
  }
  return out;
}

