/** Where README.md's anchors live: every `##` and `###` heading → the page its section goes to. */
async function readmeAnchors(): Promise<Map<string, string | null>> {
  const map = new Map<string, string | null>();
  const readme = await readFile(join(REPO, "README.md"), "utf8");
  let page: string | null = "index";
  mapLines(readme, (line, fenced) => {
    const m = fenced ? null : /^(#{2,3}) (.*)$/.exec(line);
    if (m) {
      const heading = m[2]!.trim();
      if (m[1] === "##") page = heading in README_SECTIONS ? README_SECTIONS[heading]! : "concepts";
      if (m[1] === "###" && heading in README_SECTIONS) page = README_SECTIONS[heading]!;
      map.set(githubSlug(heading), page);
    }
    return line;
  });
  return map;
}

export function href(route: string, anchor?: string): string {
  return `${route === "index" ? "/" : `/${route}`}${anchor ? `#${anchor}` : ""}`;
}

class Router {
  constructor(
    private readonly readme: Map<string, string | null>,
    private readonly adrs: Set<string>,
    /** Per published source file: GitHub anchor → Mintlify anchor. */
    private readonly anchors: Map<string, Map<string, string>>,
  ) {}

  /** The site route of a repository path (and anchor), or null when the site does not publish it. */
  route(path: string, anchor: string | undefined): string | null {
    if (path === "README.md") {
      if (!anchor) return "index";
      const page = this.readme.get(anchor);
      return page === undefined ? "index" : page;
    }
    if (FILE_PAGES[path]) return path === "docs/api-verification.md" && !existsSync(join(REPO, path)) ? null : FILE_PAGES[path]!;
    if (this.adrs.has(path)) return `contributing/adr/${posix.basename(path, ".md")}`;
    return null;
  }

  /** Rewrite one link target found in `source` (a repo-relative path). */
  rewrite(link: string, source: string): string {
    let local: string;
    if (link.startsWith(GITHUB_BLOB)) local = link.slice(GITHUB_BLOB.length);
    else if (link.startsWith(GITHUB_TREE)) local = link.slice(GITHUB_TREE.length);
    else if (/^[a-z][a-z0-9+.-]*:/i.test(link)) return link;
    else if (link.startsWith("#")) local = `${source}${link}`;
    else local = posix.normalize(posix.join(posix.dirname(source), link));
    const hash = local.indexOf("#");
    const path = (hash < 0 ? local : local.slice(0, hash)).replace(/\/$/, "") || ".";
    const anchor = hash < 0 ? undefined : local.slice(hash + 1);
    const route = this.route(path, anchor);
    if (route) return href(route, anchor && (this.anchors.get(path)?.get(anchor) ?? anchor));
    const full = join(REPO, path);
    const isDir = existsSync(full) && statSync(full).isDirectory();
    return `${isDir ? GITHUB_TREE : GITHUB_BLOB}${path}${anchor ? `#${anchor}` : ""}`;
  }
}

