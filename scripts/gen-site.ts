// Markdown → MDX

/** Code span, HTML comment: whichever starts first is taken whole. */
const TOKEN = /(`+)([\s\S]*?[^`])\1(?!`)|<!--([\s\S]*?)-->/g;

/** Escape and rewrite prose (no code spans in it). */
function prose(text: string, rewrite: (link: string) => string): string {
  return text.replace(/\]\(([^)\s]+)\)|[<{}]/g, (m, link: string | undefined) => {
    if (link !== undefined) return `](${rewrite(link)})`;
    return m === "<" ? "&lt;" : m === "{" ? "&#123;" : "&#125;";
  });
}

function comment(body: string): string {
  if (/^\s*generated:[a-z-]+:(start|end)\b/.test(body)) return "";
  return `{/* ${body.trim().replace(/\*\//g, "* /")} */}`;
}

/** Turn a run of non-fenced Markdown into MDX. */
function block(text: string, rewrite: (link: string) => string): string {
  let out = "";
  let at = 0;
  for (const m of text.matchAll(TOKEN)) {
    out += prose(text.slice(at, m.index), rewrite);
    out += m[3] !== undefined ? comment(m[3]) : m[0];
    at = m.index + m[0].length;
  }
  return out + prose(text.slice(at), rewrite);
}

/** Markdown (from `source`) → MDX body: fences kept verbatim, everything else escaped and its links rewritten. */
export function toMdx(md: string, source: string, router: Router): string {
  const rewrite = (link: string) => router.rewrite(link, source);
  const chunks: Array<{ fenced: boolean; lines: string[] }> = [];
  mapLines(md, (line, fenced) => {
    const last = chunks[chunks.length - 1];
    if (last && last.fenced === fenced) last.lines.push(line);
    else chunks.push({ fenced, lines: [line] });
    return line;
  });
  return chunks
    .map((c) => (c.fenced ? c.lines.join("\n") : block(c.lines.join("\n"), rewrite)))
    .join("\n")
    .replace(/^[ \t]*\n(?=[ \t]*\n)/gm, "") // a removed marker leaves at most one blank line
    .trim();
}

function page(route: string, meta: PageMeta, sources: string[], body: string): GeneratedFile {
  const front = [
    "---",
    `title: ${JSON.stringify(meta.title)}`,
    ...(meta.sidebarTitle ? [`sidebarTitle: ${JSON.stringify(meta.sidebarTitle)}`] : []),
    `description: ${JSON.stringify(meta.description)}`,
    "---",
    "",
    `{/* ${GENERATED_MARK} from ${sources.join(", ")}. Do not edit: edit the source and run \`pnpm site:gen\`. */}`,
    "",
  ];
  return { path: `${SITE}/${route}.mdx`, content: `${front.join("\n")}\n${body.trim()}\n` };
}

