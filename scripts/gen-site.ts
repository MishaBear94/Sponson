// Markdown helpers (fence-aware)

const FENCE = /^\s*(`{3,}|~{3,})/;

/** Map every line, telling the callback whether it is inside (or delimits) a fenced code block. */
export function mapLines(md: string, fn: (line: string, fenced: boolean) => string): string {
  let open: string | null = null;
  return md
    .split("\n")
    .map((line) => {
      const m = FENCE.exec(line);
      if (open === null && m) {
        open = m[1]!;
        return fn(line, true);
      }
      if (open !== null) {
        if (m && m[1]![0] === open[0] && m[1]!.length >= open.length && line.trim() === m[1]) open = null;
        return fn(line, true);
      }
      return fn(line, false);
    })
    .join("\n");
}

interface Section {
  heading: string;
  level: number;
  text: string;
}

/** Split at headings of exactly `level` outside fences: the text before the first one, then each section. */
export function splitSections(md: string, level: number): { preamble: string; sections: Section[] } {
  const prefix = `${"#".repeat(level)} `;
  const parts: Array<{ heading: string | null; lines: string[] }> = [{ heading: null, lines: [] }];
  mapLines(md, (line, fenced) => {
    if (!fenced && line.startsWith(prefix)) parts.push({ heading: line.slice(prefix.length).trim(), lines: [] });
    parts[parts.length - 1]!.lines.push(line);
    return line;
  });
  const [pre, ...rest] = parts;
  return { preamble: pre!.lines.join("\n"), sections: rest.map((p) => ({ heading: p.heading!, level, text: p.lines.join("\n") })) };
}

/** Drop YAML frontmatter and the first `# ` heading (with the blank line after it). */
function stripTitle(md: string): string {
  const lines = md.replace(/^---\n[\s\S]*?\n---\n/, "").split("\n");
  let at = -1;
  let i = 0;
  mapLines(lines.join("\n"), (line, fenced) => {
    if (at < 0 && !fenced && line.startsWith("# ")) at = i;
    i++;
    return line;
  });
  if (at >= 0) lines.splice(at, lines[at + 1]?.trim() === "" ? 2 : 1);
  return lines.join("\n");
}

/** The first `# ` heading's text. */
function titleOf(md: string): string {
  let title = "";
  mapLines(md, (line, fenced) => {
    if (!title && !fenced && line.startsWith("# ")) title = line.slice(2).trim();
    return line;
  });
  return title;
}

function shiftHeadings(md: string, by: number): string {
  return mapLines(md, (line, fenced) => (!fenced && /^#{1,5} /.test(line) ? "#".repeat(by) + line : line));
}

/** A heading's text as rendered: link text kept, code and emphasis markers dropped. */
function headingText(heading: string): string {
  return heading.replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").replace(/[`*]/g, "").trim();
}

/** GitHub's anchor for a heading (the same rule scripts/gen-docs.ts uses). */
export function githubSlug(heading: string): string {
  return headingText(heading)
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
}

/**
 * Mintlify's anchor for a heading, as its renderer and `mint broken-links --check-anchors` compute it (@mintlify/common
 * `slugify` + `cleanHeadingId`): whitespace becomes `-`, characters URI encoding keeps (letters, digits, `-_.!~*'()`)
 * other than letters, digits and `_` become `-` separators, everything else is kept, then `?,;:!'"()[]{}` are dropped.
 */
export function mintSlug(heading: string): string {
  const s = headingText(heading).toLowerCase().replace(/\s+/g, "-");
  const slugged = [...s]
    .map((c) => (/[a-z0-9_]/.test(c) || encodeURIComponent(c) !== c ? c : "-"))
    .join("")
    .replace(/-{2,}/g, "-")
    .replace(/^-+|-+$/g, "");
  return slugged.replace(/[?,;:!'"()[\]{}]/g, "");
}

/** The headings of a Markdown text outside fences: GitHub anchor → Mintlify anchor, duplicates numbered by each rule. */
export function headingAnchors(md: string): Map<string, string> {
  const map = new Map<string, string>();
  const gh = new Map<string, number>();
  const mint = new Map<string, number>();
  mapLines(md, (line, fenced) => {
    const m = fenced ? null : /^#{1,6}\s+(.*?)\s*#*\s*$/.exec(line);
    if (m) {
      const g = githubSlug(m[1]!);
      const ng = gh.get(g) ?? 0;
      gh.set(g, ng + 1);
      const t = mintSlug(m[1]!);
      const nt = mint.get(t) ?? 0;
      mint.set(t, nt + 1);
      map.set(ng === 0 ? g : `${g}-${ng}`, nt === 0 ? t : `${t}-${nt + 1}`);
    }
    return line;
  });
  return map;
}

