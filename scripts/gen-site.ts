/** What every generated file in site/ should contain, given the current sources. */
export async function generate(): Promise<GeneratedFile[]> {
  const adrs = (await adrFiles()).map((f) => `docs/adr/${f}`);
  const anchors = new Map<string, Map<string, string>>();
  for (const source of ["README.md", ...Object.keys(FILE_PAGES), ...adrs]) {
    if (source.endsWith(".md") && existsSync(join(REPO, source))) anchors.set(source, headingAnchors(await read(source)));
  }
  const router = new Router(await readmeAnchors(), new Set(adrs), anchors);
  const files: GeneratedFile[] = [];

  const readme = await readmePages(router);
  for (const route of ["index", "quickstart", "concepts"]) files.push(page(route, META[route]!, ["README.md"], readme.get(route)!.join("\n\n")));

  const skill = toMdx(shiftHeadings(stripTitle(await read("SKILL.md")), 1), "SKILL.md", router);
  const agents = [
    ...(readme.get("guides/agents") ?? []),
    "## The agent skill",
    `[SKILL.md](${GITHUB_BLOB}SKILL.md) is written for the agent itself: give it to the agent (as a skill, or in its instructions) and it knows when to write a plan line and when to stop for a human. Its full text follows.`,
    skill,
  ];
  files.push(page("guides/agents", META["guides/agents"]!, ["README.md", "SKILL.md"], agents.join("\n\n")));

  const whole: Array<[string, string]> = [
    ["action/README.md", "guides/github-actions"],
    ["docs/plan-format.md", "reference/plan-format"],
    ["docs/errors.md", "reference/errors"],
    ["docs/api-verification.md", "reference/api-verification"],
    ["docs/coverage.md", "reference/coverage"],
    ["CONTRIBUTING.md", "contributing/contributing"],
    ["ARCHITECTURE.md", "contributing/architecture"],
    ["docs/adr/README.md", "contributing/decisions"],
    ["SECURITY.md", "contributing/security"],
    ["ROADMAP.md", "contributing/roadmap"],
    ["CHANGELOG.md", "contributing/changelog"],
  ];
  for (const [source, route] of whole) {
    if (!existsSync(join(REPO, source))) continue;
    files.push(page(route, META[route]!, [source], toMdx(stripTitle(await read(source)), source, router)));
  }
  files.push(await examplesPage(router));
  files.push(await cliPage());
  files.push(...(await adrPages(router)));

  const config = JSON.parse(await read(`${SITE}/docs.json`)) as Record<string, unknown>;
  config.navigation = await navigation();
  files.push({ path: `${SITE}/docs.json`, content: `${JSON.stringify(config, null, 2)}\n` });
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

/** Every .mdx/.md file under site/, repo-relative. */
export async function sitePages(): Promise<string[]> {
  const out: string[] = [];
  const walk = async (dir: string): Promise<void> => {
    for (const e of await readdir(join(REPO, dir), { withFileTypes: true })) {
      const p = `${dir}/${e.name}`;
      if (e.isDirectory()) await walk(p);
      else if (/\.mdx?$/.test(e.name) && p !== `${SITE}/README.md`) out.push(p);
    }
  };
  await walk(SITE);
  return out.sort();
}

/** Generated pages on disk that the sources no longer produce. */
export async function stalePages(files: GeneratedFile[]): Promise<string[]> {
  const expected = new Set(files.map((f) => f.path));
  const stale: string[] = [];
  for (const p of await sitePages()) {
    if (!expected.has(p) && (await read(p)).includes(GENERATED_MARK)) stale.push(p);
  }
  return stale;
}

async function main(): Promise<void> {
  const files = await generate();
  for (const f of files) {
    const path = join(REPO, f.path);
    const before = await readFile(path, "utf8").catch(() => null);
    if (before === f.content) continue;
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, f.content, "utf8");
    process.stdout.write(`wrote ${f.path}\n`);
  }
  for (const p of await stalePages(files)) {
    await unlink(join(REPO, p));
    process.stdout.write(`removed ${p}\n`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e: unknown) => {
    process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
    process.exit(1);
  });
}
